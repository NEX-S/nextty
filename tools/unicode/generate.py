#!/usr/bin/env python3
"""Generate terminal width and font selection tables from pinned Unicode data."""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = json.loads((Path(__file__).with_name('SOURCES.json')).read_text())
VERSION = MANIFEST['unicode_version']


def read_inputs(directory, download):
    result = {}
    for source in MANIFEST['sources']:
        path = directory / source['file']
        if download:
            data = urlopen(source['url'], timeout=60).read()
            if hashlib.sha256(data).hexdigest() != source['sha256']:
                raise ValueError(f"Unicode input fingerprint changed: {source['file']}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != source['sha256']:
            raise ValueError(f"Unicode input fingerprint mismatch: {path}")
        result[source['file']] = data.decode('utf-8')
    return result


def properties(text):
    result = {}
    for line in text.splitlines():
        fields = line.split('#', 1)[0].strip().split(';')
        if len(fields) < 2:
            continue
        bounds = fields[0].strip().split('..')
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        result.setdefault(fields[1].strip(), set()).update(range(start, end + 1))
    return result


def generate(inputs):
    core = properties(inputs['DerivedCoreProperties.txt'])
    hangul = properties(inputs['HangulSyllableType.txt'])
    grapheme = properties(inputs['auxiliary/GraphemeBreakProperty.txt'])
    prop = properties(inputs['PropList.txt'])
    emoji = properties(inputs['emoji/emoji-data.txt'])
    east_asian = properties(inputs['EastAsianWidth.txt'])
    # Ordinary (non-CJK) terminal policy. Ambiguous codepoints stay narrow.
    zero = (core['Default_Ignorable_Code_Point'] | core['Grapheme_Extend']
            | hangul['V'] | hangul['T']
            | (grapheme['Prepend'] - prop['Prepended_Concatenation_Mark'])
            | {0x0605, 0x070F, 0x0890, 0x0891, 0x08E2, 0xA8FA})
    zero -= {0x115F, 0x2D7F}
    widths = bytearray([1]) * 0x110000
    for cp in east_asian['W'] | east_asian['F'] | {0x115F, 0x17A4}:
        widths[cp] = 2
    for cp in zero:
        widths[cp] = 0
    widths[0x17D8] = 3
    for cp in emoji['Emoji_Presentation'] | emoji['Emoji_Modifier']:
        widths[cp] = 2
    for cp in prop['Regional_Indicator']:
        widths[cp] = 1
    for cp in set(range(0x20)) | set(range(0x7F, 0xA0)):
        widths[cp] = 0
    output = ['// Generated by tools/unicode/generate.py; do not edit.',
              f'// Unicode {VERSION}. Sources/hashes and Unicode License V3: tools/unicode/.']
    # Four two-bit widths share each byte; equal 256-scalar pages share storage.
    pages, indices, packed = {}, [], []
    for offset in range(0, len(widths), 256):
        page = bytes(widths[offset:offset + 256])
        if page not in pages:
            pages[page] = len(pages)
            packed.append([sum(page[i + j] << (2 * j) for j in range(4))
                           for i in range(0, 256, 4)])
        indices.append(pages[page])
    assert len(pages) <= 256
    output.append('#[rustfmt::skip]')
    output.append(f'pub(super) const WIDTH_PAGES: &[u8; {len(indices)}] = &[')
    for offset in range(0, len(indices), 32):
        output.append('    ' + ', '.join(map(str, indices[offset:offset + 32])) + ',')
    output.append('];')
    output.append('#[rustfmt::skip]')
    output.append(f'pub(super) const WIDTH_DATA: &[[u8; 64]; {len(packed)}] = &[')
    for page in packed:
        output.append('    [')
        for offset in range(0, len(page), 16):
            output.append('        ' + ', '.join(f'0x{byte:02X}' for byte in page[offset:offset + 16]) + ',')
        output.append('    ],')
    output.append('];')
    return '\n'.join(output) + '\n'


def generate_font_data(inputs):
    values = sorted(properties(inputs['emoji/emoji-data.txt'])['Emoji_Presentation'])
    ranges = []
    for cp in values:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    output = ['/* Generated by tools/unicode/generate.py; do not edit.',
              f' * Unicode {VERSION}; sources and Unicode License V3: tools/unicode/. */',
              '#ifndef NEXTTY_FONT_DATA_H', '#define NEXTTY_FONT_DATA_H',
              '#include <stdint.h>', '',
              'static const uint32_t nt_emoji_presentation[][2] = {']
    output.extend(f'    {{0x{start:X}, 0x{end:X}}},' for start, end in ranges)
    output.extend(['};', '', '#endif', ''])
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=ROOT / f'target/unicode-{VERSION}')
    parser.add_argument('--download', action='store_true', help='fetch pinned official inputs')
    parser.add_argument('--check', action='store_true', help='compare without updating generated tables')
    args = parser.parse_args()
    inputs = read_inputs(args.data, args.download)
    outputs = {ROOT / 'src/width_tables.rs': generate(inputs),
               ROOT / 'native/font_data.h': generate_font_data(inputs)}
    for output, generated in outputs.items():
        if args.check:
            if output.read_text() != generated:
                raise SystemExit(f'{output.relative_to(ROOT)} is not up to date')
        else:
            output.write_text(generated)
            print(f'wrote {output.relative_to(ROOT)} ({len(generated)} bytes)')
    if args.check:
        print(f'Unicode {VERSION} tables match all pinned inputs')


if __name__ == '__main__':
    main()
